document.addEventListener('DOMContentLoaded', function () {
  var nodes = document.querySelectorAll('[data-i18n]');
  nodes.forEach(function (el) {
    el.setAttribute('data-i18n-it', el.innerHTML);
  });

  function setLang(lang) {
    nodes.forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (lang === 'en' && window.TS_EN[key] !== undefined) {
        el.innerHTML = window.TS_EN[key];
      } else {
        el.innerHTML = el.getAttribute('data-i18n-it');
      }
    });
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('.lang-btn').forEach(function (b) {
      b.classList.toggle('active', b.getAttribute('data-lang') === lang);
    });
    try { localStorage.setItem('ts-lang', lang); } catch (e) {}
  }

  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.addEventListener('click', function () {
      setLang(btn.getAttribute('data-lang'));
    });
  });

  var saved = 'it';
  try { saved = localStorage.getItem('ts-lang') || 'it'; } catch (e) {}
  setLang(saved);
});
